            public static long GetTotalXp(int skillPoint, TrainingState training)
            {
                Dictionary<int, long> table =
                    training == TrainingState.Specialized
                        ? Specialized
                        : Trained;


                return table.TryGetValue(skillPoint, out long xp)
                    ? xp
                    : 0;
            }


            public static long GetXpForNextSkillPoint(
                int currentSkillPoint,
                TrainingState training)
            {
                return GetTotalXp(currentSkillPoint + 1, training);
            }


            public static long GetRemainingXpForSkillPoint(
                int currentSkillPoint,
                long currentXp,
                TrainingState training)
            {
                long nextSkillPointXp =
                    GetXpForNextSkillPoint(
                        currentSkillPoint,
                        training);


                if (nextSkillPointXp <= currentXp)
                {
                    return 0;
                }


                return nextSkillPointXp - currentXp;
            }


            public static int GetSkillPointFromXp(
                long xp,
                bool specialized)
            {
                var table = specialized ? Specialized : Trained;

                int currentSkillPoint = 0;


                foreach (var entry in table)
                {
                    if (xp >= entry.Value)
                    {
                        currentSkillPoint = entry.Key;
                    }
                    else
                    {
                        break;
                    }
                }


                return currentSkillPoint;
            }


            public static long GetXpToNextSkillPoint(
                long xp,
                bool specialized)
            {
                var table = specialized ? Specialized : Trained;


                int currentSkillPoint =
                    GetSkillPointFromXp(
                        xp,
                        specialized);


                int nextSkillPoint =
                    currentSkillPoint + 1;


                if (!table.ContainsKey(nextSkillPoint))
                {
                    return 0;
                }


                return table[nextSkillPoint] - xp;
            }


            public static double GetPercentToNextSkillPoint(
                long xp,
                bool specialized)
            {
                var table = specialized ? Specialized : Trained;


                int currentSkillPoint =
                    GetSkillPointFromXp(
                        xp,
                        specialized);


                int nextSkillPoint =
                    currentSkillPoint + 1;


                if (!table.ContainsKey(nextSkillPoint))
                {
                    return 100.0;
                }


                long currentSkillPointXp =
                    table[currentSkillPoint];


                long nextSkillPointXp =
                    table[nextSkillPoint];


                long range =
                    nextSkillPointXp - currentSkillPointXp;


                long progress =
                    xp - currentSkillPointXp;


                return Math.Round(
                    ((double)progress / range) * 100,
                    2);
            }

